type param struct {
	Name     string
	Type     string
	Required bool
	Multi    bool
	Since    string
}

type command struct {
	Name    string
	Since   string
	Args    []param
	Options []param
}

type release struct {
	Version  string
	Commands []command
}

var paramRe = regexp.MustCompile(`^([A-Za-z0-9]+)\('([^'?*+]+)([?*+]?)'(.*)\)$`)

var autofillRe = regexp.MustCompile(`(^|, )autofill=True(,|$)`)

// parse reads one API.txt; only command, arg and option lines matter.
func parse(r io.Reader) ([]command, error) {
	var cmds []command
	sc := bufio.NewScanner(r)
	sc.Buffer(nil, 1<<20)
	for n := 1; sc.Scan(); n++ {
		kind, rest, _ := strings.Cut(sc.Text(), ": ")
		switch kind {
		case "command":
			name, _, _ := strings.Cut(rest, "/")
			if name == "" {
				return nil, fmt.Errorf("line %d: empty command name", n)
			}
			cmds = append(cmds, command{Name: name})
		case "arg", "option":
			if len(cmds) == 0 {
				return nil, fmt.Errorf("line %d: %s before any command", n, kind)
			}
			m := paramRe.FindStringSubmatch(rest)
			if m == nil {
				return nil, fmt.Errorf("line %d: cannot parse %q", n, rest)
			}
			p := param{
				Name:     m[2],
				Type:     m[1],
				Required: (m[3] == "" || m[3] == "+") && !autofillRe.MatchString(m[4]),
				Multi:    m[3] == "*" || m[3] == "+",
			}
			c := &cmds[len(cmds)-1]
			if kind == "arg" {
				c.Args = append(c.Args, p)
			} else {
				c.Options = append(c.Options, p)
			}
		}
	}
	return cmds, sc.Err()
}

func parseVersion(s string) (v [3]int, ok bool) {
	parts := strings.Split(s, ".")
	if len(parts) != 3 {
		return v, false
	}
	for i, p := range parts {
		n, err := strconv.Atoi(p)
		if err != nil {
			return v, false
		}
		v[i] = n
	}
	return v, true
}

func compareVersions(a, b string) int {
	va, _ := parseVersion(a)
	vb, _ := parseVersion(b)
	return slices.Compare(va[:], vb[:])
}

// allowedRemovals are dropped from the catalogue: FreeIPA 4.9.9 removed this
// no-op option, and a validator rejecting it on 4.9.0-4.9.8 costs nothing.
var allowedRemovals = map[string]bool{
	"automember_default_group_remove\x00option\x00description": true,
	"automember_default_group_set\x00option\x00description":    true,
}

// merge folds releases into one catalogue with the newest release's params
// and the first release that had each name as its Since. A name that
// disappears again is an error: a single Since could not describe it.
func merge(rels []release, allowed map[string]bool) ([]command, []string, error) {
	rels = slices.Clone(rels)
	slices.SortFunc(rels, func(a, b release) int { return compareVersions(a.Version, b.Version) })
	since := map[string]string{} // "cmd", "cmd\x00arg\x00name", "cmd\x00option\x00name"
	removed := map[string]bool{}
	var latest []command
	for _, rel := range rels {
		seen := map[string]bool{}
		for _, c := range rel.Commands {
			seen[c.Name] = true
			for kind, ps := range map[string][]param{"arg": c.Args, "option": c.Options} {
				for _, p := range ps {
					seen[c.Name+"\x00"+kind+"\x00"+p.Name] = true
				}
			}
		}
		var keys []string
		for k := range since {
			switch {
			case seen[k] && removed[k]:
				f := strings.Split(k, "\x00")
				return nil, nil, fmt.Errorf("%s: %s %s %q reappears", rel.Version, f[0], f[1], f[2])
			case seen[k]:
			case allowed[k]:
				removed[k] = true
			default:
				keys = append(keys, k)
			}
		}
		if len(keys) > 0 {
			slices.Sort(keys)
			f := strings.Split(keys[0], "\x00")
			if len(f) == 1 {
				return nil, nil, fmt.Errorf("%s: command %s removed", rel.Version, f[0])
			}
			return nil, nil, fmt.Errorf("%s: %s %s %q removed", rel.Version, f[0], f[1], f[2])
		}
		for k := range seen {
			if _, ok := since[k]; !ok {
				since[k] = rel.Version
			}
		}
		latest = rel.Commands
	}
	for k := range allowed {
		if !removed[k] {
			return nil, nil, fmt.Errorf("stale allow-list entry %q: no such removal in the data", strings.ReplaceAll(k, "\x00", " "))
		}
	}
	out := make([]command, 0, len(latest))
	for _, c := range latest {
		c.Since = since[c.Name]
		c.Args = withSince(c.Args, since, c.Name+"\x00arg\x00")
		c.Options = withSince(c.Options, since, c.Name+"\x00option\x00")
		out = append(out, c)
	}
	slices.SortFunc(out, func(a, b command) int { return cmp.Compare(a.Name, b.Name) })
	versions := make([]string, len(rels))
	for i, r := range rels {
		versions[i] = r.Version
	}
	return out, versions, nil
}

func withSince(ps []param, since map[string]string, prefix string) []param {
	out := slices.Clone(ps)
	for i := range out {
		out[i].Since = since[prefix+out[i].Name]
	}
	return out
}

func render(cmds []command, versions []string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by gencatalogue; DO NOT EDIT.\n\npackage ipa\n\n")
	fmt.Fprintf(&b, "var catalogueReleases = %#v\n\n", versions)
	b.WriteString("var catalogue = []Command{\n")
	for _, c := range cmds {
		fmt.Fprintf(&b, "{Name: %q, Since: %q, Args: %s, Options: %s},\n", c.Name, c.Since, renderParams(c.Args), renderParams(c.Options))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func renderParams(ps []param) string {
	if len(ps) == 0 {
		return "nil"
	}
	var b strings.Builder
	b.WriteString("[]Param{\n")
	for _, p := range ps {
		fmt.Fprintf(&b, "{%q, %q, %t, %t, %q},\n", p.Name, p.Type, p.Required, p.Multi, p.Since)
	}
	b.WriteString("}")
	return b.String()
}
